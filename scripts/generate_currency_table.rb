#!/usr/bin/ruby
# frozen_string_literal: true

# Generates src/mica/decimal/currency_table.cr from the ISO 4217 list of
# current currencies ("List one"), as published by SIX, the ISO 4217
# maintenance agency:
#
#   https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
#
# The snapshot read is scripts/iso4217/list-one.xml; its sha256 is pinned
# below and checked before the file is read. To take a newer list, download
# it over the snapshot, update SOURCE_SHA256, run this script and review the
# diff of the table.
#
#   /usr/bin/ruby scripts/generate_currency_table.rb
#
# The list has one row per country or entity; a currency used in several
# places (EUR, USD) appears once in the table. A minor unit of "N.A." (gold,
# SDR, test and fund codes) becomes nil.
#
# Only the Ruby standard library is used (system /usr/bin/ruby).

require 'digest'
require 'rexml/document'

ROOT = File.expand_path('..', __dir__)
SOURCE = File.join(ROOT, 'scripts/iso4217/list-one.xml')
SOURCE_SHA256 = '33139b438657d1cee116ba737807ea71d19d6de4b90f799a09c56f0cc6a1b0ff'
OUTPUT = File.join(ROOT, 'src/mica/decimal/currency_table.cr')

bytes = File.binread(SOURCE)
observed = Digest::SHA256.hexdigest(bytes)
abort "generate_currency_table: #{SOURCE} has sha256 #{observed}, expected #{SOURCE_SHA256}" unless observed == SOURCE_SHA256

document = REXML::Document.new(bytes)
published = document.root.attributes['Pblshd'] or abort 'generate_currency_table: no Pblshd date in the list'

entries = {}
REXML::XPath.each(document, '//CcyNtry') do |row|
  code = row.elements['Ccy']&.text
  next if code.nil? # entities with no universal currency (Antarctica)

  numeric = row.elements['CcyNbr'].text
  minor = row.elements['CcyMnrUnts'].text
  abort "generate_currency_table: bad code #{code.inspect}" unless code.match?(/\A[A-Z]{3}\z/)
  abort "generate_currency_table: bad numeric code #{numeric.inspect} for #{code}" unless numeric.match?(/\A\d{3}\z/)
  minor_units = minor == 'N.A.' ? 'nil' : Integer(minor, 10).to_s
  entry = [numeric.to_i, minor_units]
  if entries.key?(code) && entries[code] != entry
    abort "generate_currency_table: #{code} has two definitions: #{entries[code].inspect} and #{entry.inspect}"
  end
  entries[code] = entry
end

width = entries.keys.map { |code| code.inspect.size }.max
lines = entries.sort.map do |code, (numeric, minor_units)|
  "      #{code.inspect.ljust(width)} => new(#{code.inspect}, #{numeric}, #{minor_units}),"
end

header = <<~CRYSTAL
  # GENERATED by scripts/generate_currency_table.rb from the ISO 4217 list
  # of current currencies published #{published} (scripts/iso4217/list-one.xml,
  # sha256 #{SOURCE_SHA256}).
  # Do not edit by hand: change the snapshot and run the script again.
  module Mica
    struct Currency
      # Every current ISO 4217 currency by alpha code: #{entries.size} codes.
      TABLE = {
CRYSTAL
footer = [
  "    }",
  "",
  "    # The publication date of the ISO 4217 list the table was made from.",
  "    TABLE_PUBLISHED = #{published.inspect}",
  "  end",
  "end",
].join("\n")
File.write(OUTPUT, "#{header}#{lines.join("\n")}\n#{footer}\n")

puts "wrote #{entries.size} currencies (ISO 4217 list published #{published}) to #{OUTPUT}"
