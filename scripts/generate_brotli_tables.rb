# Writes src/mica/brotli/tables.cr (the RFC 7932 transforms and the
# literal context lookup table) and copies the static dictionary to
# src/mica/brotli/dictionary.bin, from a google/brotli source tree.
#
#   /usr/bin/ruby scripts/generate_brotli_tables.rb /path/to/brotli
#
# The tree must be google/brotli v1.2.1 (commit
# db24a98aed38a16de78cc05ca15cdd8dc2a0d92d); each input file is checked
# against its sha256 before it is read.

require "digest"
require "fileutils"

SOURCE_COMMIT = "db24a98aed38a16de78cc05ca15cdd8dc2a0d92d"
PINNED = {
  "c/common/transform.c" => "47f229a79c3542ea57ec07145d7eaf77300a02816d95695332f9911ea19d6ab3",
  "c/common/context.c" => "c9aa1acb35af38c90c4a38ba168885b649838236b2d57adb5e76d687bdbe252e",
  "c/common/dictionary.bin" => "20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70",
}.freeze

root = ARGV.fetch(0) { abort "usage: generate_brotli_tables.rb BROTLI_SOURCE_DIR" }
here = File.expand_path("..", __dir__)

PINNED.each do |path, sha|
  actual = Digest::SHA256.file(File.join(root, path)).hexdigest
  abort "#{path}: sha256 #{actual}, expected #{sha}" unless actual == sha
end

# Unescapes a C string literal body (the escapes transform.c uses).
def c_string(body)
  bytes = []
  scanner = 0
  while scanner < body.bytesize
    char = body.getbyte(scanner)
    if char != 92 # backslash
      bytes << char
      scanner += 1
      next
    end
    following = body[scanner + 1]
    case following
    when "x"
      hex = body[scanner + 2, 2]
      bytes << hex.to_i(16)
      scanner += 4
    when "n" then bytes << 10; scanner += 2
    when "t" then bytes << 9; scanner += 2
    when "\"" then bytes << 34; scanner += 2
    when "'" then bytes << 39; scanner += 2
    when "\\" then bytes << 92; scanner += 2
    else
      octal = body[scanner + 1..][/\A[0-7]{1,3}/]
      abort "unknown escape at #{scanner}" unless octal
      bytes << octal.to_i(8)
      scanner += 1 + octal.size
    end
  end
  bytes
end

transform_c = File.read(File.join(root, "c/common/transform.c"), mode: "rb")
prefix_block = transform_c[/kPrefixSuffix\[217\] =(.*?);/m, 1] or abort "kPrefixSuffix not found"
prefix_suffix = prefix_block.scan(/"((?:[^"\\]|\\.)*)"/m).map { |(body)| c_string(body) }.flatten
prefix_suffix << 0 # the implicit trailing zero
abort "kPrefixSuffix has #{prefix_suffix.size} bytes" unless prefix_suffix.size == 217

map_block = transform_c[/kPrefixSuffixMap\[50\] = \{(.*?)\};/m, 1] or abort "kPrefixSuffixMap not found"
prefix_suffix_map = map_block.scan(/0x([0-9A-F]+)/).map { |(hex)| hex.to_i(16) }
abort "kPrefixSuffixMap has #{prefix_suffix_map.size} entries" unless prefix_suffix_map.size == 50

kinds = {
  "IDENTITY" => 0, "UPPERCASE_FIRST" => 10, "UPPERCASE_ALL" => 11,
}
(1..9).each do |count|
  kinds["OMIT_LAST_#{count}"] = count
  kinds["OMIT_FIRST_#{count}"] = 11 + count
end
data_block = transform_c[/kTransformsData\[\] = \{(.*?)\};/m, 1] or abort "kTransformsData not found"
triples = data_block.scan(/(\d+),\s*BROTLI_TRANSFORM_(\w+),\s*(\d+)/).map do |prefix, kind, suffix|
  [prefix.to_i, kinds.fetch(kind), suffix.to_i]
end
abort "kTransformsData has #{triples.size} transforms" unless triples.size == 121

# Prefix and suffix strings: a length byte, then that many bytes.
def string_at(prefix_suffix, map, id)
  start = map.fetch(id)
  prefix_suffix[start + 1, prefix_suffix[start]]
end

context_c = File.read(File.join(root, "c/common/context.c"), mode: "rb")
lut_block = context_c[/_kBrotliContextLookupTable\[2048\] = \{(.*?)\};/m, 1] or abort "context table not found"
lut = lut_block.gsub(%r{/\*.*?\*/}m, "").scan(/\d+/).map(&:to_i)
abort "context table has #{lut.size} entries" unless lut.size == 2048

def crystal_bytes(values, per_line = 16, indent = "      ")
  values.each_slice(per_line).map { |slice| indent + slice.map { |v| "#{v}_u8" }.join(", ") + "," }.join("\n")
end

transform_lines = triples.map do |prefix, kind, suffix|
  pre = string_at(prefix_suffix, prefix_suffix_map, prefix)
  suf = string_at(prefix_suffix, prefix_suffix_map, suffix)
  "      Transform.new(Bytes[#{pre.join(", ")}], #{kind}_u8, Bytes[#{suf.join(", ")}]),"
end

source = <<~CRYSTAL
  # GENERATED by scripts/generate_brotli_tables.rb from google/brotli v1.2.1
  # (commit #{SOURCE_COMMIT}): c/common/transform.c
  # (sha256 #{PINNED["c/common/transform.c"]}) and c/common/context.c
  # (sha256 #{PINNED["c/common/context.c"]}). Do not edit by hand.
  module Mica::Brotli
    # :nodoc:
    module Tables
      # One word transform (RFC 7932, Appendix B): a prefix, an elementary
      # transform and a suffix. *kind* is 0 (identity), 1 to 9 (omit the
      # last N bytes), 10 (uppercase the first character), 11 (uppercase
      # every character) or 12 to 20 (omit the first N - 11 bytes).
      record Transform, prefix : Bytes, kind : UInt8, suffix : Bytes

      # The 121 transforms, in transform-ID order.
      TRANSFORMS = [
  #{transform_lines.join("\n")}
      ]

      # The literal context lookup table (RFC 7932, section 7.1): for
      # context mode M, the context ID is
      # `CONTEXT_LOOKUP[M * 512 + p1] | CONTEXT_LOOKUP[M * 512 + 256 + p2]`.
      CONTEXT_LOOKUP = Bytes[
  #{crystal_bytes(lut)}
      ]
    end
  end
CRYSTAL

File.write(File.join(here, "src/mica/brotli/tables.cr"), source)
FileUtils.cp(File.join(root, "c/common/dictionary.bin"), File.join(here, "src/mica/brotli/dictionary.bin"))
puts "wrote src/mica/brotli/tables.cr (#{triples.size} transforms, #{lut.size} context entries) and dictionary.bin"
