# Writes spec/regex/fixtures/static_corpus.cr: every distinct
# (pattern, case-insensitive) pair of the benchmark corpora (Amber, ReDoS,
# and the rebar cases bench/regex/scripts/rebar_corpus.rb fetched and
# verified) as a `Mica::Regex.static` call, with the haystacks the corpus
# itself carries (rebar's inline haystacks, the ReDoS families' attack
# strings). spec/regex/static_corpus_differential_spec.cr searches them.
#
#   /usr/bin/ruby bench/regex/scripts/rebar_corpus.rb
#   /usr/bin/ruby scripts/write_static_corpus.rb
#
# A pattern the runtime compiler rejects (under
# `CompileLimits::TRUSTED_PATTERN`) is a compile error for
# `Mica::Regex.static`, so each pattern is first classified by the
# build-time program (src/mica/regex/static/emit_static_pattern.cr), and
# the rejected ones are listed in the fixture's header instead.
require "json"
require "open3"
require "tmpdir"

ROOT = File.expand_path("..", __dir__)
OUTPUT = File.join(ROOT, "spec/regex/fixtures/static_corpus.cr")
# The longest inline haystack kept, in bytes.
MAX_HAYSTACK_BYTES = 4096
# The ReDoS attack lengths searched (units repeated).
LIST_OF_ATTACK_LENGTHS = [0, 1, 2, 3, 5, 8, 13, 21].freeze

# A Crystal string literal holding exactly *text*.
def crystal_literal(text)
  body = text.each_char.map do |char|
    case char
    when "\"" then "\\\""
    when "\\" then "\\\\"
    when "#" then "\\#"
    else
      char.ord < 0x20 || char.ord == 0x7F ? format("\\u{%X}", char.ord) : char
    end
  end.join
  "\"#{body}\""
end

entries = {}
add = lambda do |id, pattern, insensitive, haystacks|
  key = [pattern, insensitive]
  entry = entries[key] ||= { id: id, pattern: pattern, insensitive: insensitive, haystacks: [] }
  entry[:haystacks].concat(haystacks)
end

amber = JSON.parse(File.read(File.join(ROOT, "bench/regex/corpus/amber.json")))
amber["patterns"].each do |entry|
  add.call("amber/#{entry["generator"]}/#{entry["name"]}", entry["pattern"], entry["case_insensitive"] == true, [])
end

redos = JSON.parse(File.read(File.join(ROOT, "bench/regex/corpus/redos.json")))
redos["families"].each do |family|
  haystacks = LIST_OF_ATTACK_LENGTHS.map { |length| family["prepend"] + family["unit"] * length + family["append"] }
  add.call("redos/#{family["name"]}", family["pattern"], false, haystacks)
end

rebar_json = Dir[File.join(ROOT, "bench/data/regex/rebar-*/rebar.json")].first
abort "run /usr/bin/ruby bench/regex/scripts/rebar_corpus.rb first" unless rebar_json
rebar = JSON.parse(File.read(rebar_json))
rebar["cases"].each do |entry|
  haystack = entry["haystack"]
  inline = []
  if haystack.is_a?(Hash) && haystack["contents"]
    text = haystack["contents"] * [haystack["repeat"] || 1, 1].max + (haystack["append"] || "")
    inline << text if text.bytesize <= MAX_HAYSTACK_BYTES && text.valid_encoding?
  end
  add.call("rebar/#{entry["id"]}", entry["pattern"], entry["case_insensitive"] == true, inline)
end

emitter = File.join(Dir.tmpdir, "mica_emit_static_pattern")
system("crystal-alpha", "build", "--release", File.join(ROOT, "src/mica/regex/static/emit_static_pattern.cr"),
  "-o", emitter, exception: true)
list_of_rejected = []
entries.reject! do |_, entry|
  output, status = Open3.capture2(emitter, entry[:pattern], entry[:insensitive] ? "1" : "0")
  abort "#{emitter} failed on #{entry[:id]}" unless status.success?
  kind, note = output.split("\n", 3)
  next false unless kind == "error"
  list_of_rejected << "#{entry[:id]}: #{note}"
  true
end

File.open(OUTPUT, "w") do |file|
  file.puts "# Generated by scripts/write_static_corpus.rb from bench/regex/corpus/amber.json,"
  file.puts "# bench/regex/corpus/redos.json and #{File.basename(File.dirname(rebar_json))}/rebar.json."
  file.puts "# Do not edit by hand."
  file.puts "#"
  file.puts "# Left out: the runtime compiler rejects these, so Mica::Regex.static does not compile them:"
  list_of_rejected.each { |line| file.puts "# - #{line}" }
  file.puts "STATIC_CORPUS = [] of StaticCorpus::Entry"
  entries.each_value do |entry|
    literal = crystal_literal(entry[:pattern])
    haystacks = entry[:haystacks].uniq.map { |text| crystal_literal(text) }.join(", ")
    file.puts "STATIC_CORPUS << StaticCorpus::Pattern.new(#{crystal_literal(entry[:id])}, #{literal}, #{entry[:insensitive]},"
    file.puts "  Mica::Regex.static(#{literal}, ignore_case: #{entry[:insensitive]}), [#{haystacks}] of String)"
  end
end
puts "wrote #{OUTPUT}: #{entries.size} patterns (#{list_of_rejected.size} left out)"
