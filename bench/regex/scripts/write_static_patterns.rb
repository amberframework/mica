# Writes bench/data/regex/static_patterns.cr for the mica-static runner
# (bench/regex/mica_static_runner.cr): one `Mica::Regex.static` constant per
# distinct (pattern, case-insensitive) pair of the Amber, ReDoS and rebar
# corpora, an index from each pair to its constant, and a `compile` that
# wraps the constant in the harness's adapter. A pattern the runtime
# compiler rejects is left out (`Mica::Regex.static` would not compile
# it), so the runner reports it as unsupported, as the mica runner does.
#
#   /usr/bin/ruby bench/regex/scripts/write_static_patterns.rb [OUT.cr]
#
# bench/regex/run.sh runs it when --engines names mica-static.
require "json"
require "open3"
require "tmpdir"

ROOT = File.expand_path("../../..", __dir__)
output_path = ARGV[0] || File.join(ROOT, "bench/data/regex/static_patterns.cr")

# A Crystal string literal holding exactly *text*.
def crystal_literal(text)
  body = text.each_char.map do |char|
    case char
    when "\"" then "\\\""
    when "\\" then "\\\\"
    when "#" then "\\#"
    else
      char.ord < 0x20 || char.ord == 0x7F ? format("\\u{%X}", char.ord) : char
    end
  end.join
  "\"#{body}\""
end

pairs = []
amber = JSON.parse(File.read(File.join(ROOT, "bench/regex/corpus/amber.json")))
amber["patterns"].each { |entry| pairs << [entry["pattern"], entry["case_insensitive"] == true] }
redos = JSON.parse(File.read(File.join(ROOT, "bench/regex/corpus/redos.json")))
redos["families"].each { |family| pairs << [family["pattern"], false] }
rebar_json = Dir[File.join(ROOT, "bench/data/regex/rebar-*/rebar.json")].first
abort "run /usr/bin/ruby bench/regex/scripts/rebar_corpus.rb first" unless rebar_json
JSON.parse(File.read(rebar_json))["cases"].each { |entry| pairs << [entry["pattern"], entry["case_insensitive"] == true] }
pairs.uniq!

emitter = File.join(Dir.tmpdir, "mica_emit_static_pattern")
system("crystal-alpha", "build", "--release", File.join(ROOT, "src/mica/regex/static/emit_static_pattern.cr"),
  "-o", emitter, exception: true)
rejected = 0
pairs.reject! do |pattern, insensitive|
  output, status = Open3.capture2(emitter, pattern, insensitive ? "1" : "0")
  abort "#{emitter} failed on #{pattern[0, 60].inspect}" unless status.success?
  rejected += 1 if output.start_with?("error\n")
  output.start_with?("error\n")
end

File.open(output_path, "w") do |file|
  file.puts "# Generated by bench/regex/scripts/write_static_patterns.rb. Do not edit by hand."
  file.puts "module RegexBench::StaticPatterns"
  pairs.each_with_index do |(pattern, insensitive), index|
    file.puts "  PATTERN_#{index} = Mica::Regex.static(#{crystal_literal(pattern)}, ignore_case: #{insensitive})"
  end
  file.puts
  file.puts "  INDEX = {"
  pairs.each_with_index do |(pattern, insensitive), index|
    file.puts "    {#{crystal_literal(pattern)}, #{insensitive}} => #{index},"
  end
  file.puts "  } of {String, Bool} => Int32"
  file.puts
  file.puts "  # The adapter for the pattern compiled for (*pattern*, *case_insensitive*), or nil."
  file.puts "  def self.compile(pattern : String, case_insensitive : Bool, limits : Mica::Regex::SearchLimits,"
  file.puts "                   deadline : Time::Span?) : CompiledPattern?"
  file.puts "    case INDEX[{pattern, case_insensitive}]?"
  pairs.each_index do |index|
    file.puts "    when #{index} then CompiledStaticPattern.build(PATTERN_#{index}, limits, deadline)"
  end
  file.puts "    end"
  file.puts "  end"
  file.puts "end"
end
puts "wrote #{output_path}: #{pairs.size} static patterns (#{rejected} rejected by the runtime compiler)"
