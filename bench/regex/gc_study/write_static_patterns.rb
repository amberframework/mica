# Writes bench/data/regex/static_patterns.cr: one `Mica::Regex.static` per
# distinct (pattern, case-insensitive) pair of the cases named in a case
# list, for bench/regex/mica_static_runner.cr.
#
#   /usr/bin/ruby bench/regex/gc_study/write_static_patterns.rb CASE_LIST OUT.cr
#
# CASE_LIST holds one case id per line (see run_study.sh).
require "json"

root = File.expand_path("../../..", __dir__)
case_list_path, output_path = ARGV
abort "usage: write_static_patterns.rb CASE_LIST OUT.cr" unless case_list_path && output_path
wanted = File.readlines(case_list_path, chomp: true).reject(&:empty?).to_h { |id| [id, true] }

pairs = []
amber = JSON.parse(File.read(File.join(root, "bench/regex/corpus/amber.json")))
amber["patterns"].each do |entry|
  prefix = "amber/#{entry["generator"]}/#{entry["name"]}@"
  next unless wanted.keys.any? { |id| id.start_with?(prefix) }
  pairs << [entry["pattern"], entry["case_insensitive"] == true]
end
rebar_json = Dir[File.join(root, "bench/data/regex/rebar-*/rebar.json")].first
abort "run bench/regex/scripts/rebar_corpus.rb first" unless rebar_json
JSON.parse(File.read(rebar_json))["cases"].each do |entry|
  next unless wanted[entry["id"]]
  pairs << [entry["pattern"], entry["case_insensitive"] == true]
end
pairs.uniq!

# A Crystal string literal with exactly the pattern's characters.
def crystal_literal(text)
  body = text.each_char.map do |char|
    case char
    when "\"" then "\\\""
    when "\\" then "\\\\"
    when "#" then "\\#"
    else
      char.ord < 0x20 || char.ord == 0x7F ? format("\\u{%X}", char.ord) : char
    end
  end.join
  "\"#{body}\""
end

File.open(output_path, "w") do |file|
  file.puts "# Generated by bench/regex/gc_study/write_static_patterns.rb from #{File.basename(case_list_path)}."
  file.puts "module RegexBench::StaticPatterns"
  file.puts "  def self.table : Hash({String, Bool}, CompiledPattern)"
  file.puts "    table = {} of {String, Bool} => CompiledPattern"
  pairs.each do |pattern, insensitive|
    literal = crystal_literal(pattern)
    file.puts "    begin"
    file.puts "      table[{#{literal}, #{insensitive}}] = CompiledStaticPattern.new(Mica::Regex.static(#{literal}, ignore_case: #{insensitive}))"
    file.puts "    rescue Mica::Error"
    file.puts "    end"
  end
  file.puts "    table"
  file.puts "  end"
  file.puts "end"
end
puts "wrote #{output_path}: #{pairs.size} static patterns"
