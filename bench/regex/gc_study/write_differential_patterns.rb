# Writes the pattern table of the static differential
# (bench/regex/gc_study/static_differential.cr) from the JSON lines
# list_differential_patterns.cr prints.
#
#   /usr/bin/ruby bench/regex/gc_study/write_differential_patterns.rb PATTERNS.jsonl OUT.cr
require "json"

input, output = ARGV
abort "usage: write_differential_patterns.rb PATTERNS.jsonl OUT.cr" unless input && output

def crystal_literal(text)
  body = text.each_char.map do |char|
    case char
    when "\"" then "\\\""
    when "\\" then "\\\\"
    when "#" then "\\#"
    else char.ord < 0x20 || char.ord == 0x7F ? format("\\u{%X}", char.ord) : char
    end
  end.join
  "\"#{body}\""
end

rows = File.readlines(input).map { |line| JSON.parse(line) }
File.open(output, "w") do |file|
  file.puts "# Generated by bench/regex/gc_study/write_differential_patterns.rb (#{rows.size} patterns)."
  file.puts "module StaticDifferential"
  file.puts "  def self.list_of_entries : Array(Entry)"
  file.puts "    list = [] of Entry"
  rows.each do |row|
    literal = crystal_literal(row["source"])
    file.puts "    begin"
    file.puts "      list << Entry.new(#{literal}, #{row["ignore_case"]}, #{row["origin"].inspect}, Adapter.new(Mica::Regex.static(#{literal}, ignore_case: #{row["ignore_case"]})))"
    file.puts "    rescue Mica::Error"
    file.puts "    end"
  end
  file.puts "    list"
  file.puts "  end"
  file.puts "end"
end
puts "wrote #{output}: #{rows.size} patterns"
